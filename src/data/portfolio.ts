// ── 항목 추가/수정 방법 ──────────────────────────────────────────
// 1) thumbnail: public/portfolio/<id>.png 에 캡처 이미지를 넣는다(없으면 브랜드색 폴백).
// 2) liveUrl: 살아있는 주소를 넣으면 카드 클릭 시 새 탭으로 이동.
